    def test_frozen_policy_caps_and_fields_cannot_be_relaxed(self):
        for kind in ("docx", "xlsx"):
            for key, maximum in FROZEN["policies"][kind]["config"].items():
                if key == "reader_limits":
                    cases = [(key, field, cap + 1) for field, cap in maximum.items()]
                else:
                    cases = [(key, None, maximum + 1)]
                for field, nested, value in cases:
                    with self.subTest(kind=kind, field=field, nested=nested):
                        data = json.loads(canonical(FROZEN["policies"][kind]))
                        if nested:
                            data["config"][field][nested] = value
                        else:
                            data["config"][field] = value
                        with self.assertRaises(codec.CodecError):
                            a0._policy_object(codec.Spec(codec.canonical_dumps(data)))

    def test_tightened_policy_fingerprints_match_independent_A_vectors(self):
        cases = (("docx", "9f5ad87532f18da33eb62ca525537905ed544c1a77ed99148f277cb81c6e5a03",
                  "e958f7117992894712f727cb7b9d6501adad40850ea7c5fca5d857caed6eec7a"),
                 ("xlsx", "5e7e836510e405c617c65e7260dddf9fc6e16eec13e37287f540882d8d87ca7f",
                  "c62783f9c845367ead67d7960e91918cd067f69c15caf70aabf362f5cdb7561e"))
        for kind, fingerprint, spec_hash in cases:
            data = json.loads(canonical(FROZEN["policies"][kind]))
            config = data["config"]
            config["reader_limits"]["max_file_bytes"] = 1048576
            config.update({"max_sources": 8, "max_id_chars": 32} if kind == "docx" else
                          {"max_scope_rows": 50, "max_history_units": 1024})
            spec = codec.Spec(codec.canonical_dumps(data))
            self.assertEqual(spec.sha256, spec_hash)
            self.assertEqual(a0._policy_object(spec).fingerprint, fingerprint)

