def sha(raw):
    return hashlib.sha256(raw).hexdigest()


@unittest.skipUnless(os.name == "nt", "Reviewed A0 requires Windows fixed NTFS/ReFS")
class HistoricalLedgerTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.temp = tempfile.TemporaryDirectory(prefix="grundschutz-ai-a0-replay-")
        cls.base = Path(cls.temp.name) / "a0.sqlite"
        raw = (Path(__file__).parent / "fixtures/a0-ledger.sql").read_bytes()
        if sha(raw) != SQL_SHA256:
            cls.temp.cleanup()
            raise AssertionError("Literal A-produced fixture SQL changed")
        # Trusted test artifact only, never production or DB-supplied commands.
        with closing(sqlite3.connect(cls.base)) as connection:
            connection.executescript(raw.decode("utf-8"))

    @classmethod
    def tearDownClass(cls):
        cls.temp.cleanup()

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="grundschutz-ai-a0-case-")
        self.addCleanup(self.temp.cleanup)
        self.path = Path(self.temp.name) / "copy.sqlite"
        shutil.copyfile(self.base, self.path)

    def load(self, **kwargs):
        return compat.load_historical_ledger(self.path, **kwargs)

    def mutate(self, action):
        with closing(sqlite3.connect(self.path)) as connection:
            triggers = connection.execute("SELECT name,sql FROM sqlite_master WHERE type='trigger'").fetchall()
            for name, _ in triggers:
                connection.execute("DROP TRIGGER " + name)
            action(connection)
            for _, sql in triggers:
                connection.execute(sql)
            connection.commit()

    def refuse(self, **kwargs):
        before = self.path.read_bytes()
        with self.assertRaises(compat.HistoricalLedgerError):
            self.load(**kwargs)
        self.assertEqual(before, self.path.read_bytes())

    def rewrite(self, sequence, change):
        """Coherently rehash payload/event/entire following chain, not old oracle."""
        def action(connection):
            rows = connection.execute("SELECT * FROM events ORDER BY sequence").fetchall()
            previous = None
            for row in rows:
                envelope = codec.canonical_loads(row[-1])
                if row[0] == sequence:
                    payload = codec.canonical_loads(connection.execute(
                        "SELECT content FROM content_blobs WHERE sha256=?", (row[7],)).fetchone()[0])
                    change(payload, envelope)
                    raw = codec.canonical_dumps(payload)
                    key = sha(raw)
                    connection.execute("INSERT OR IGNORE INTO content_blobs VALUES (?,?,?)", (key, len(raw), raw))
                    if key != envelope["payload_sha256"]:
                        # Keep the attack coherent: rejection must not depend
                        # on leaving the obsolete payload as an orphan BLOB.
                        connection.execute("DELETE FROM content_blobs WHERE sha256=?",
                                           (envelope["payload_sha256"],))
                    envelope["payload_sha256"] = key
                    envelope["payload_codec"] = payload["payload_codec"]
                envelope["previous_event_sha256"] = previous
                envelope.pop("event_sha256")
                previous = codec.fingerprint("ledger-event/v2", envelope)
                envelope["event_sha256"] = previous
                names = ("sequence event_id transaction_id transaction_index transaction_count kind payload_codec "
                         "payload_sha256 previous_event_sha256 event_sha256 occurred_at actor_id").split()
                connection.execute("DELETE FROM events WHERE sequence=?", (row[0],))
                connection.execute("INSERT INTO events VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)",
                                   tuple(envelope[key] for key in names) + (codec.canonical_dumps(envelope),))
            connection.execute("UPDATE store_metadata SET last_event_hash=?", (previous,))
        self.mutate(action)

    def unknown_implementation(self, transform):
        """A coherent genesis+registration-only history with an unknown Spec."""
        descriptor = json.loads(canonical(FROZEN["descriptors"]["docx"]))
        transform(descriptor)
        spec = codec.Spec(codec.canonical_dumps(descriptor))
        def action(connection):
            genesis = connection.execute("SELECT * FROM events WHERE sequence=1").fetchone()
            metadata = list(connection.execute("SELECT * FROM store_metadata").fetchone())
            genesis_payload = connection.execute("SELECT content FROM content_blobs WHERE sha256=?", (genesis[7],)).fetchone()[0]
            for table in a0.schema.TABLES:
                connection.execute("DELETE FROM " + table)
            payload = codec.make_payload(codec.EventKind.IMPLEMENTATION,
                                         implementation_hash=spec.sha256,
                                         descriptor_blob_sha256=sha(spec.canonical))
            envelope = codec.make_envelope(payload, store_uuid=format(1, "032x"), sequence=2,
                                           previous=genesis[9], event_id=format(4, "032x"),
                                           transaction_id=format(5, "032x"),
                                           occurred_at="2026-11-10T12:00:00.000000Z",
                                           actor_id="synthetic:compat-reviewer")
            for raw in (genesis_payload, spec.canonical, payload.canonical):
                connection.execute("INSERT INTO content_blobs VALUES (?,?,?)", (sha(raw), len(raw), raw))
            connection.execute("INSERT INTO implementation_specs VALUES (?,?)", (spec.sha256, sha(spec.canonical)))
            connection.execute("INSERT INTO events VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)", genesis)
            data = envelope.data()
            names = ("sequence event_id transaction_id transaction_index transaction_count kind payload_codec "
                     "payload_sha256 previous_event_sha256 event_sha256 occurred_at actor_id").split()
            connection.execute("INSERT INTO events VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)",
                               tuple(data[key] for key in names) + (envelope.canonical,))
            metadata[-2:] = (2, data["event_sha256"])
            connection.execute("INSERT INTO store_metadata VALUES (?,?,?,?,?,?,?,?)", metadata)
        self.mutate(action)

    def test_literal_A_fixture_reconstructs_complete_state_and_vectors(self):
        before = self.path.read_bytes()
        state = self.load()
        self.assertEqual((state.head.sequence, state.head.event_sha256), (13, HEAD))
        for event, pair in zip(state.events, FROZEN["event_hashes"], strict=True):
            self.assertEqual((sha(event.payload.canonical), event.envelope.data()["event_sha256"]), tuple(pair))
        with closing(sqlite3.connect(self.path)) as connection:
            projections = {table: sorted((portable(row) for row in connection.execute("SELECT * FROM " + table)),
                                        key=canonical) for table in a0.schema.TABLES}
        manifest = {"producer_commit": "2ee9bc7cf309727e5a9f10e2982791dbc991c464",
                    "state": state_manifest(state), "projections": projections}
        self.assertEqual(sha(canonical(manifest)), MANIFEST_SHA256)
        self.assertEqual(before, self.path.read_bytes())

    def test_original_A_created_database_cross_version_readonly_proof(self):
        supplied = os.environ.get("GRUNDSCHUTZ_A0_ORACLE")
        if not supplied:
            self.skipTest("Set GRUNDSCHUTZ_A0_ORACLE to the independently A-created oracle.sqlite")
        path = Path(supplied)
        before = path.read_bytes()
        self.assertEqual(sha(before), ORIGINAL_DB_SHA256)
        expected_manifest = (path.parent / "oracle-manifest.json").read_bytes()
        self.assertEqual(sha(expected_manifest), MANIFEST_SHA256)
        state = compat.load_historical_ledger(path)
        self.assertEqual(state_manifest(state), json.loads(expected_manifest)["state"])
        self.assertEqual(state, self.load())
        self.assertEqual(before, path.read_bytes())

    def test_highest_pending_and_failed_heads_do_not_fall_back(self):
        state = self.load()
        for suffix, revision, number, status in (("docx", 2, 17, "pending"),
                                                ("xlsx", 1, 26, "pending"),
                                                ("missing", 1, 31, "failed")):
            ref = state.source_head("synthetic:compat-a0-" + suffix)
            self.assertEqual((ref.revision, ref.registration_id), (revision, format(number, "032x")))
            self.assertEqual(state.registration(ref).status.value, status)
        old = next(r for r in state.registrations if r.ref.registration_id == format(10, "032x"))
        self.assertEqual(old.status.value, "failed")
        self.assertEqual(old.failure_codes, ("operator_failed",))
        self.assertEqual({b.content for b in state.original_blobs}, set(RAW.values()))

